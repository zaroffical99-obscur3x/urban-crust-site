export const formatRs = (n: number) => `${n.toLocaleString("en-PK")} Rs`;

export const buildWhatsAppOrder = (
  items: { name: string; variant?: string; qty: number; price: number }[],
  customer: { name: string; phone: string; address: string; note?: string; payment: string }
) => {
  const lines = items.map(
    (it, i) =>
      `${i + 1}. ${it.name}${it.variant ? ` (${it.variant})` : ""} x${it.qty} = ${it.qty * it.price} Rs`
  );
  const total = items.reduce((s, it) => s + it.qty * it.price, 0);
  const msg = [
    `*NEW ORDER — URBAN CRUST*`,
    `--------------------------`,
    ...lines,
    `--------------------------`,
    `*Total: ${total} Rs*`,
    ``,
    `*Name:* ${customer.name}`,
    `*Phone:* ${customer.phone}`,
    `*Address:* ${customer.address}`,
    `*Payment:* ${customer.payment}`,
    customer.note ? `*Note:* ${customer.note}` : ``,
    ``,
    `Please confirm my order. Thank you!`,
  ]
    .filter(Boolean)
    .join("\n");
  return `https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(msg)}`;
};
